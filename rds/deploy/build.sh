#!/usr/bin/env bash
# Assembles rds/database/ into the install scripts uploaded to APEX SQL Scripts.
#
#   rds/deploy/build.sh
#
# RDS is reached only through APEX, so the install is a handful of files to
# upload rather than one SQLcl run. The sources stay one file per object, as
# everywhere else in this repository, and this stitches them together in load
# order. The outputs are committed so they can be uploaded straight from a
# checkout - but edit the sources and rebuild, never the outputs.
#
# Two package scripts rather than one, to keep each upload well under any
# instance's script size limit.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
src="$here/../database"

emit() {
    local out="$1" title="$2"; shift 2
    {
        printf -- '-- %s\n--\n' "$title"
        printf -- '-- GENERATED by rds/deploy/build.sh from rds/database/. Do not edit -\n'
        printf -- '-- change the sources and rebuild. Run in APEX: SQL Workshop > SQL Scripts.\n\n'
        for f in "$@"; do
            printf -- '-- ==== %s\n\n' "${f#"$src"/}"
            cat "$f"
            printf '\n'
        done
    } > "$here/$out"
    echo "wrote rds/deploy/$out ($(wc -c < "$here/$out") bytes)"
}

emit 01_install_tables.sql "Tables, configuration seed and RDS views" \
    "$src"/10_tables/*.sql "$src"/15_views/*.sql

emit 02_install_packages_1.sql "Packages 01-07: configuration through the HTTP client" \
    "$src"/20_packages/0[1-7]_*.sql

emit 03_install_packages_2.sql "Packages 08-15: SKU reads through the API entry point" \
    "$src"/20_packages/0[89]_*.sql "$src"/20_packages/1[0-9]_*.sql
