prompt Creating Office style-composition POC objects

-- Reference data and capture tables for the Office POC console (app 103).
--
-- These belong to the *calling* system, not to the integration layer. The POC
-- composes an MFCS item number from a style and a supplier colour and sends the
-- result; the controller accepts a number, it does not invent one. That split is
-- the whole point - a composition rule living in the controller would have to
-- know every caller's scheme, which is what MAP.* was and why it was retired.
--
-- Style mirrors MFCS UDA 66040 (LV, 13,693 values on UAT). Supplier colour and
-- its codes mirror UDAs 56038 and 61038, which are FF - free-form text with no
-- value list in MFCS - so the list is maintained here and MFCS is simply told
-- what was chosen.

create table poc_style_model (
    style_no    varchar2(20) not null,
    style_desc  varchar2(250) not null,
    active_yn   varchar2(1) default 'Y' not null,
    source      varchar2(60) default 'UAT_UDA_66040' not null,
    loaded_at   timestamp with time zone default systimestamp not null,
    constraint poc_style_model_pk primary key (style_no),
    constraint poc_style_model_active_ck check (active_yn in ('Y', 'N'))
);

-- "on null" is load-bearing on every identity column here. APEX form and grid
-- automatic row processing sends the primary key explicitly as NULL on insert,
-- and a plain "generated by default as identity" rejects that with ORA-01400
-- rather than generating a value.
create table poc_supplier_colour (
    colour_id    number generated by default on null as identity,
    colour_name  varchar2(120) not null,
    active_yn    varchar2(1) default 'Y' not null,
    constraint poc_supplier_colour_pk primary key (colour_id),
    constraint poc_supplier_colour_uk unique (colour_name),
    constraint poc_supplier_colour_active_ck check (active_yn in ('Y', 'N'))
);

-- A code belongs to a colour, so the screen's code list cascades from the colour
-- choice. Chosen over two independent lists because the code composes the item
-- number while the colour composes the description: picked separately, a planner
-- could pair a name with a code that does not belong to it, and the resulting
-- style would carry a number and a description that disagree - permanently, since
-- the number is burned at create.
create table poc_supplier_colour_code (
    colour_code_id  number generated by default on null as identity,
    colour_id       number not null,
    colour_code     varchar2(10) not null,
    code_desc       varchar2(120),
    active_yn       varchar2(1) default 'Y' not null,
    constraint poc_supplier_colour_code_pk primary key (colour_code_id),
    constraint poc_supplier_colour_code_fk foreign key (colour_id)
        references poc_supplier_colour (colour_id) on delete cascade,
    constraint poc_supplier_colour_code_uk unique (colour_code),
    constraint poc_supplier_colour_code_ck check (active_yn in ('Y', 'N'))
);

create index poc_supplier_colour_code_ix on poc_supplier_colour_code (colour_id);

-- One style being captured. The composed values are stored rather than derived on
-- read: once a request has gone to MFCS, what was sent must stay legible even if
-- the reference rows are later edited.
create table poc_style_draft (
    draft_id            number generated by default on null as identity,
    style_no            varchar2(20),
    colour_id           number,
    colour_code_id      number,
    -- The MFCS colour *differentiator*, which is not the supplier colour above.
    -- The diff defines the SKU and must be one the tenant holds (DIFF_C in
    -- MASTER_DATA); the supplier colour composes the number and description.
    -- Two colour notions on one style, and merging them would be easy to do.
    mfcs_colour         varchar2(60),
    department          number,
    class               number,
    subclass            number,
    supplier            number,
    origin_country      varchar2(3),
    currency_code       varchar2(3),
    unit_cost           number,
    retail_price        number,
    composed_item_no    varchar2(25),
    composed_item_desc  varchar2(250),
    action_request_id   varchar2(80),
    draft_status        varchar2(30) default 'DRAFT' not null,
    http_status         number,
    request_payload     clob,
    response_payload    clob,
    created_by          varchar2(255),
    created_at          timestamp with time zone default systimestamp not null,
    last_updated_at     timestamp with time zone default systimestamp not null,
    constraint poc_style_draft_pk primary key (draft_id),
    constraint poc_style_draft_style_fk foreign key (style_no)
        references poc_style_model (style_no),
    constraint poc_style_draft_colour_fk foreign key (colour_id)
        references poc_supplier_colour (colour_id),
    constraint poc_style_draft_code_fk foreign key (colour_code_id)
        references poc_supplier_colour_code (colour_code_id),
    constraint poc_style_draft_status_ck check (draft_status in
        ('DRAFT', 'SUBMITTED', 'COMPLETED', 'FAILED'))
);

-- The size curve. SKU_SIZE is a differentiator id (DIFF_S in MASTER_DATA), not a
-- display size - the same rule the existing console follows, because eight size
-- descriptions on this tenant map to more than one differentiator.
create table poc_style_draft_sku (
    draft_sku_id       number generated by default on null as identity,
    draft_id           number not null,
    sku_size           varchar2(60) not null,
    sku_qty            number default 1 not null,
    composed_sku_no    varchar2(25),
    composed_sku_desc  varchar2(250),
    constraint poc_style_draft_sku_pk primary key (draft_sku_id),
    constraint poc_style_draft_sku_fk foreign key (draft_id)
        references poc_style_draft (draft_id) on delete cascade,
    constraint poc_style_draft_sku_uk unique (draft_id, sku_size),
    constraint poc_style_draft_sku_qty_ck check (sku_qty > 0)
);

create index poc_style_draft_sku_ix on poc_style_draft_sku (draft_id);
