-- Phase two of the Office POC: everything app 102 captures, an order section,
-- and a two-stage gate before anything reaches MFCS.
--
-- The gate is the point of this file. A draft is worked on, then *submitted for
-- review*, then *approved*, and only approval sends. Submitting freezes the
-- document; approving replays the frozen one rather than rebuilding it, so what
-- the approver saw is what MFCS receives. Rebuilding at approval would make the
-- approval meaningless, and it is the same reasoning that makes resume replay a
-- stored payload rather than re-derive one.

alter table poc_style_draft add (
    -- CREATE_STYLE, or CREATE_ALL when an order rides along. MODIFY_ORDER when
    -- the draft was seeded from an order that already exists.
    operation_name    varchar2(30)  default 'CREATE_STYLE' not null,
    -- COMPOSED when the style number was built here from a style and a colour,
    -- AMENDED when the draft was populated by reading MFCS. An amended draft has
    -- no composition behind it, so the capture screen must not offer to redo one.
    origin            varchar2(20)  default 'COMPOSED' not null,
    style             varchar2(30),
    source_order_ref  varchar2(120),
    order_no          varchar2(30),
    delivery_loc      number,
    import_country    varchar2(3),
    not_before_date   date,
    not_after_date    date,
    otb_eow_date      date,
    earliest_ship_date date,
    latest_ship_date  date,
    submitted_by      varchar2(120),
    submitted_at      timestamp with time zone,
    approved_by       varchar2(120),
    approved_at       timestamp with time zone
);

-- DRAFT is editable, SUBMITTED is frozen apart from order quantities, APPROVED is
-- frozen outright and on its way to MFCS.
alter table poc_style_draft drop constraint poc_style_draft_status_ck;
alter table poc_style_draft add constraint poc_style_draft_status_ck
    check (draft_status in ('DRAFT', 'SUBMITTED', 'APPROVED', 'COMPLETED', 'FAILED'));

alter table poc_style_draft add constraint poc_style_draft_operation_ck
    check (operation_name in ('CREATE_STYLE', 'CREATE_ALL', 'MODIFY_ORDER'));

alter table poc_style_draft add constraint poc_style_draft_origin_ck
    check (origin in ('COMPOSED', 'AMENDED'));

-- Style-level attributes. SKUs inherit their style's UDAs, seasons and tariff
-- codes - the backend writes the same set to the parent and every child - so
-- there is deliberately no SKU-level table for any of them. Images are written to
-- the style only, because MFCS cascades those itself and rejects the child copy.
create table poc_draft_uda (
    draft_uda_id  number generated by default on null as identity,
    draft_id      number not null,
    uda_id        varchar2(30) not null,
    uda_value     varchar2(120),
    uda_text      varchar2(250),
    uda_date      date,
    constraint poc_draft_uda_pk primary key (draft_uda_id),
    constraint poc_draft_uda_fk foreign key (draft_id)
        references poc_style_draft (draft_id) on delete cascade,
    constraint poc_draft_uda_uk unique (draft_id, uda_id)
);

create table poc_draft_sku_upc (
    draft_upc_id  number generated by default on null as identity,
    draft_sku_id  number not null,
    upc           varchar2(30) not null,
    upc_type      varchar2(10) default 'EAN13' not null,
    primary_yn    varchar2(1)  default 'N' not null,
    constraint poc_draft_sku_upc_pk primary key (draft_upc_id),
    constraint poc_draft_sku_upc_fk foreign key (draft_sku_id)
        references poc_style_draft_sku (draft_sku_id) on delete cascade,
    constraint poc_draft_sku_upc_uk unique (upc),
    constraint poc_draft_sku_upc_ck check (primary_yn in ('Y', 'N'))
);

create table poc_draft_season (
    draft_season_id number generated by default on null as identity,
    draft_id        number not null,
    season_id       number not null,
    phase_id        number,
    sequence_no     number,
    constraint poc_draft_season_pk primary key (draft_season_id),
    constraint poc_draft_season_fk foreign key (draft_id)
        references poc_style_draft (draft_id) on delete cascade
);

create table poc_draft_image (
    draft_image_id   number generated by default on null as identity,
    draft_id         number not null,
    image_name       varchar2(120) not null,
    image_address    varchar2(250),
    image_type       varchar2(10),
    primary_yn       varchar2(1) default 'N' not null,
    display_priority number,
    constraint poc_draft_image_pk primary key (draft_image_id),
    constraint poc_draft_image_fk foreign key (draft_id)
        references poc_style_draft (draft_id) on delete cascade,
    constraint poc_draft_image_ck check (primary_yn in ('Y', 'N'))
);

create table poc_draft_hts (
    draft_hts_id   number generated by default on null as identity,
    draft_id       number not null,
    hts            varchar2(30) not null,
    import_country varchar2(3),
    origin_country varchar2(3),
    effect_from    date,
    effect_to      date,
    constraint poc_draft_hts_pk primary key (draft_hts_id),
    constraint poc_draft_hts_fk foreign key (draft_id)
        references poc_style_draft (draft_id) on delete cascade
);

create index poc_draft_uda_ix on poc_draft_uda (draft_id);
create index poc_draft_season_ix on poc_draft_season (draft_id);
create index poc_draft_image_ix on poc_draft_image (draft_id);
create index poc_draft_hts_ix on poc_draft_hts (draft_id);
create index poc_draft_sku_upc_ix on poc_draft_sku_upc (draft_sku_id);

-- Who may review and who may approve. Invented for the POC; a real deployment
-- would read this from whatever owns identity. Kept as one table with two flags
-- rather than two tables, because the dual-approval rule to come is about one
-- person not doing both on the same draft, which is easier to enforce when they
-- are drawn from one list.
create table poc_approver (
    approver_id  number generated by default on null as identity,
    full_name    varchar2(120) not null,
    email        varchar2(240),
    can_submit_yn varchar2(1) default 'Y' not null,
    can_approve_yn varchar2(1) default 'Y' not null,
    active_yn    varchar2(1) default 'Y' not null,
    constraint poc_approver_pk primary key (approver_id),
    constraint poc_approver_uk unique (full_name),
    constraint poc_approver_submit_ck check (can_submit_yn in ('Y', 'N')),
    constraint poc_approver_approve_ck check (can_approve_yn in ('Y', 'N')),
    constraint poc_approver_active_ck check (active_yn in ('Y', 'N'))
);

